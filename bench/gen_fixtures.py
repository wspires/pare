#!/usr/bin/env python3
"""Write tests/data/mask.tsv: proto/pare.py's mask() on real record heads.

    python3 bench/gen_fixtures.py

`cargo test` checks the Rust masks against this file, so a masking
difference shows up as the exact line and both results, without Python
installed. The lines are the record heads of every corpus log (unique, a
deterministic sample) plus lines built from characters where Python's and
Rust's character classes differ. Regenerate after a change to the Python
masks (which the port's rules freeze) or to pick a new sample.

Each row: input, mask(input), mask(input, words=False), with backslash,
tab and newline escaped as \\\\, \\t and \\n.
"""

import glob
import io
import os
import random
import sys
import tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "proto"))
import pare  # noqa: E402

SAMPLE = 4000


def esc(s: str) -> str:
    return s.replace("\\", "\\\\").replace("\t", "\\t").replace("\n", "\\n")


def heads() -> list[str]:
    """Every record head in the corpora, cleaned, unique, in a fixed sample."""
    seen: dict[str, None] = {}
    logs = []
    for pat in ("corpus/*.log", "corpus-generated/*.log", "corpus-dev/*/*.log", "corpus-heldout/*/*.log"):
        logs += sorted(glob.glob(os.path.join(ROOT, pat)))
    with tempfile.TemporaryDirectory() as tmp:
        spool = os.path.join(tmp, "spool")
        for path in logs:
            with open(path, "rb") as f:
                data = f.read()
            store, _ = pare.analyze(io.BytesIO(data), width=200, spool_path=spool)
            raw = data.split(b"\n")
            for start in store.rstart:
                seen.setdefault(pare.clean_line(raw[start].decode("utf-8", errors="replace")), None)
    lines = sorted(seen)
    random.Random(723).shuffle(lines)
    return lines[:SAMPLE]


def awkward() -> list[str]:
    out = []
    for i in range(40):
        out.append(f"job{i} x\u0301{i} 5\u00b2 v1.2\u0301 a\u0301/b {i}\u00b9 \u0e50{i} \U00016ac0{i} \u203f{i} "
                   f"10.0.0.{i}\u0301 2026-10-0{i % 9 + 1}\u0301 0xff\u00b2 caf\u00e9{i} \u212a{i} worker\u00b3")
    out += ["", "   ", "\u001f lead and trail \u001c", "=====  -----  ......  ___", "1/30 10/7/26 Tue Oct 7 Oct 7, 2026"]
    return out


def main() -> None:
    lines = heads() + awkward()
    os.makedirs(os.path.join(ROOT, "tests", "data"), exist_ok=True)
    path = os.path.join(ROOT, "tests", "data", "mask.tsv")
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(f"# generated by bench/gen_fixtures.py from proto/pare.py's mask(); {len(lines)} rows\n")
        for line in lines:
            f.write(f"{esc(line)}\t{esc(pare.mask(line))}\t{esc(pare.mask(line, words=False))}\n")
    print(f"wrote {path}: {len(lines)} rows")


if __name__ == "__main__":
    main()
