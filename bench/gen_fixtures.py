#!/usr/bin/env python3
"""Write the golden files in tests/data/ from proto/pare.py.

    python3 bench/gen_fixtures.py

- mask.tsv: mask() on real record heads.
- vocab.tsv: severity, vocabulary classes and vocab_score() on real lines.
- vocab.txt, vocab-example.txt: --dump-vocab, built-in and with
  proto/vocab.example applied.

`cargo test` checks the Rust port against these files, so a difference
shows up as the exact line and both results, without Python installed.

mask.tsv: The lines are the record heads of every corpus log (unique, a
deterministic sample) plus lines built from characters where Python's and
Rust's character classes differ. Regenerate after a change to the Python
masks (which the port's rules freeze) or to pick a new sample.

Each row: input, mask(input), mask(input, words=False), with backslash,
tab and newline escaped as \\\\, \\t and \\n.

vocab.tsv: every line of the corpora (unique, a deterministic sample) plus
awkward ones. Each row: the line, its severity (-1 for none), the classes
it has (the letters of CLASS_LETTERS), and vocab_score() as a head and as a
body line, written with repr() so they read back to the same float.
"""

import glob
import io
import os
import random
import sys
import tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "proto"))
import pare  # noqa: E402

SAMPLE = 4000
VOCAB_SAMPLE = 6000
CLASS_LETTERS = {"error": "e", "warn": "w", "summary": "s", "frame": "f", "pass": "p", "noise": "n", "advice": "a",
                 "strong-error": "x"}


def esc(s: str) -> str:
    return s.replace("\\", "\\\\").replace("\t", "\\t").replace("\n", "\\n")


def logs() -> list[str]:
    out = []
    for pat in ("corpus/*.log", "corpus-generated/*.log", "corpus-dev/*/*.log", "corpus-heldout/*/*.log"):
        out += sorted(glob.glob(os.path.join(ROOT, pat)))
    return out


def all_lines() -> list[str]:
    """Every line in the corpora, cleaned, unique, in a fixed sample."""
    seen: dict[str, None] = {}
    for path in logs():
        with open(path, "rb") as f:
            for raw in f.read().split(b"\n"):
                seen.setdefault(pare.clean_line(raw.decode("utf-8", errors="replace")), None)
    lines = sorted(seen)
    random.Random(724).shuffle(lines)
    return lines[:VOCAB_SAMPLE]


def awkward_vocab() -> list[str]:
    return [
        "\u0130NFO started", "[\u0131nfo] x", "level=\u0130nfo", "\u212aILLED by oom", "ERROR\u0345 x",
        "GET /x \u0665\u0660\u0663", "exit code \u0661", "exited with status -9", "rc=0", "status: 404",
        "E/Tag( 12): boom", "E0921 10:11:12.000 1 x.cc:1] boom", "E   assert 1 == 2", "[E] x", "I/O error",
        "  at com.x.Assert.fail(Assert.java:1)", '  File "a.py", line 3, in test_error', "[ERROR]", "  ERROR  ",
        "0 errors, 0 warnings", "no failures found", "re-run with -e", "Warning: deprecated thing",
        "error[E0308]: mismatched types", "build ok", "PASSED test_x", "\u2713 works", "100% done...",
        "\u017fEVERE problem", "Fehler: Zeit\u00fcberschreitung", "x\u0301error", "_error_ e_rror",
    ]


def heads() -> list[str]:
    """Every record head in the corpora, cleaned, unique, in a fixed sample."""
    seen: dict[str, None] = {}
    with tempfile.TemporaryDirectory() as tmp:
        spool = os.path.join(tmp, "spool")
        for path in logs():
            with open(path, "rb") as f:
                data = f.read()
            store, _ = pare.analyze(io.BytesIO(data), width=200, spool_path=spool)
            raw = data.split(b"\n")
            for start in store.rstart:
                seen.setdefault(pare.clean_line(raw[start].decode("utf-8", errors="replace")), None)
    lines = sorted(seen)
    random.Random(723).shuffle(lines)
    return lines[:SAMPLE]


def awkward() -> list[str]:
    out = []
    for i in range(40):
        out.append(f"job{i} x\u0301{i} 5\u00b2 v1.2\u0301 a\u0301/b {i}\u00b9 \u0e50{i} \U00016ac0{i} \u203f{i} "
                   f"10.0.0.{i}\u0301 2026-10-0{i % 9 + 1}\u0301 0xff\u00b2 caf\u00e9{i} \u212a{i} worker\u00b3")
    out += ["", "   ", "\u001f lead and trail \u001c", "=====  -----  ......  ___", "1/30 10/7/26 Tue Oct 7 Oct 7, 2026"]
    return out


def main() -> None:
    lines = heads() + awkward()
    os.makedirs(os.path.join(ROOT, "tests", "data"), exist_ok=True)
    path = os.path.join(ROOT, "tests", "data", "mask.tsv")
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(f"# generated by bench/gen_fixtures.py from proto/pare.py's mask(); {len(lines)} rows\n")
        for line in lines:
            f.write(f"{esc(line)}\t{esc(pare.mask(line))}\t{esc(pare.mask(line, words=False))}\n")
    print(f"wrote {path}: {len(lines)} rows")

    lines = all_lines() + awkward_vocab()
    path = os.path.join(ROOT, "tests", "data", "vocab.tsv")
    v = pare.VOCAB
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(f"# generated by bench/gen_fixtures.py from proto/pare.py's Vocab and vocab_score(); {len(lines)} rows\n")
        for line in lines:
            sev = v.severity(line)
            classes = "".join(letter for cls, letter in CLASS_LETTERS.items() if v.has(cls, line)) or "-"
            head = pare.vocab_score(line, head=True, sev=sev)
            body = pare.vocab_score(line, head=False, sev=sev)
            f.write(f"{esc(line)}\t{-1 if sev is None else sev}\t{classes}\t{head!r}\t{body!r}\n")
    print(f"wrote {path}: {len(lines)} rows")

    for name, text in (("vocab.txt", None), ("vocab-example.txt", "proto/vocab.example")):
        entries = pare.DEFAULT_VOCAB
        if text:
            with open(os.path.join(ROOT, text), encoding="utf-8") as f:
                entries = pare.parse_vocab(f.read(), entries, source=text)
        path = os.path.join(ROOT, "tests", "data", name)
        with open(path, "w", encoding="utf-8", newline="\n") as f:
            f.write(pare.dump_vocab(entries))
        print(f"wrote {path}")


if __name__ == "__main__":
    main()
