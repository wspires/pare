#!/usr/bin/env python3
"""Write src/pyunicode.rs: Python's character classes, as tables for Rust.

    python3.13 bench/gen_pyunicode.py > src/pyunicode.rs

The Rust port must decide "is this a word character / digit / space" exactly
as proto/pare.py does, and Python's definitions differ from Rust's: re's \\w
is str.isalnum() or "_" (Rust's regex counts combining marks and connector
punctuation too, and leaves out other numbers such as superscripts), \\d and
str.isdigit() follow Python's Unicode version, and str.isspace() has U+001C
to U+001F. So the classes are taken from the Python that is the reference,
written as sorted ranges, and checked into the repository.

Regenerate with the Python version the reference is defined by (the one CI
runs parity with, 3.13); the version is written into the file, and CI
checks that the file is what this script writes.
"""

import re
import sys
import unicodedata

CLASSES = [
    ("WORD", r"re's \w in a str pattern: str.isalnum() or '_'", lambda c, w=re.compile(r"\w"): bool(w.match(c))),
    ("DECIMAL", r"re's \d in a str pattern: decimal digits (Nd)", lambda c, d=re.compile(r"\d"): bool(d.match(c))),
    ("SPACE", r"re's \s in a str pattern, and str.isspace()", lambda c, s=re.compile(r"\s"): bool(s.match(c))),
    ("DIGIT", "str.isdigit(): decimal digits and other digits (superscripts, circled)", str.isdigit),
]


def ranges(pred) -> list[tuple[int, int]]:
    out, start = [], None
    for cp in range(0x110001):
        ok = cp < 0x110000 and not 0xD800 <= cp < 0xE000 and pred(chr(cp))
        if ok and start is None:
            start = cp
        elif not ok and start is not None:
            out.append((start, cp - 1))
            start = None
    return out


def main() -> None:
    # isspace must agree with \s, or the two uses would drift apart.
    assert ranges(str.isspace) == ranges(CLASSES[2][2])
    w = sys.stdout.write
    w("//! Python's character classes, generated by `bench/gen_pyunicode.py`; do not edit.\n")
    w("//!\n")
    py = "%d.%d" % sys.version_info[:2]
    w(f"//! From Python {py}, Unicode {unicodedata.unidata_version}. Each table is a\n")
    w("//! sorted list of inclusive code point ranges; [`crate::pyclass`] looks them\n")
    w("//! up and turns them into regex classes.\n\n")
    w(f'/// The Unicode version the tables come from.\npub const UNICODE_VERSION: &str = "{unicodedata.unidata_version}";\n')
    w(f'/// The Python version the tables come from.\npub const PYTHON_VERSION: &str = "{py}";\n')
    for name, doc, pred in CLASSES:
        rs = ranges(pred)
        w(f"\n/// {doc} ({len(rs)} ranges).\n#[rustfmt::skip]\npub const {name}: &[(u32, u32)] = &[\n")
        for i in range(0, len(rs), 6):
            w("    " + " ".join(f"(0x{a:X}, 0x{b:X})," for a, b in rs[i:i + 6]) + "\n")
        w("];\n")


if __name__ == "__main__":
    main()
